/**
 * Writes `migrations/0002_text.sql`: text functions for any pack's rules and moves, with the
 * Unicode classes Postgres regex lacks spelled out from this Node's tables. `text.test.ts` fails
 * when the file and this output differ. Run: `pnpm -F @brandfactory/core exec tsx scripts/text-functions.ts`.
 */
import { realpathSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { bracket } from './unicode-class'

export function textFunctionsSql(): string {
  const pictograph = `${bracket(/\p{Extended_Pictographic}/u)}\\ufe0f?`
  const word = bracket(/[\p{L}\p{N}]/u, '_')
  const letterOrDigit = bracket(/[\p{L}\p{N}]/u)
  return `-- Generated by scripts/text-functions.ts; do not edit by hand.
-- Text functions any pack's rules and moves may call. Unicode classes come from Node's tables:
-- Extended_Pictographic (emoji), and letters and digits (\\p{L}, \\p{N}).

CREATE SCHEMA textfn;
GRANT USAGE ON SCHEMA textfn TO pack_runtime;

-- The text without emoji (and the variation selector that may follow one).
CREATE FUNCTION textfn.strip_emoji(t text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN regexp_replace(t, E'${pictograph}', '', 'g');

-- The text without hashtags (# followed by letters, digits or _).
CREATE FUNCTION textfn.strip_hashtags(t text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN regexp_replace(t, E'#${word}+', '', 'g');

-- The hashtags in the text, in order.
CREATE FUNCTION textfn.hashtags(t text) RETURNS text[]
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN array(SELECT m[1] FROM regexp_matches(t, E'(#${word}+)', 'g') AS m);

-- The text up to its first '.', '!', '?' or emoji.
CREATE FUNCTION textfn.first_sentence(t text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN (regexp_split_to_array(t, E'[.!?]|${pictograph}'))[1];

-- True when the text holds at least one letter or digit.
CREATE FUNCTION textfn.has_word(t text) RETURNS boolean
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN t ~ E'${letterOrDigit}';

GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA textfn TO pack_runtime;
`
}

const here = path.dirname(fileURLToPath(import.meta.url))
export const TEXT_MIGRATION = path.resolve(here, '../migrations/0002_text.sql')

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(TEXT_MIGRATION, textFunctionsSql())
}
